import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import Ajv from 'ajv';
import standalone from 'ajv/dist/standalone/index.js';

const schema = JSON.parse(readFileSync(new URL('../config/rules.schema.json', import.meta.url), 'utf8'));
const ajv = new Ajv({ strict: true, allErrors: true, code: { source: true } });
const code = '// Generated by pnpm rules:generate; do not edit.\n' + standalone(ajv, ajv.compile(schema));
const target = new URL('../src/generated/rules-validator.cjs', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== code) throw new Error('Schema validator is stale. Run pnpm rules:generate.');
} else {
  mkdirSync(new URL('../src/generated/', import.meta.url), { recursive: true });
  writeFileSync(target, code);
}
